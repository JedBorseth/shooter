/// Where a shot landed on a body.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum HitZone {
    Head,
    /// Neck, chest, and shoulders.
    Chest,
    Stomach,
    Arm,
    Leg,
}

impl HitZone {
    pub const ALL: [HitZone; 5] = [
        HitZone::Head,
        HitZone::Chest,
        HitZone::Stomach,
        HitZone::Arm,
        HitZone::Leg,
    ];

    /// Name used in collider metadata (`hit_zone`) and debug output.
    pub fn name(self) -> &'static str {
        match self {
            HitZone::Head => "head",
            HitZone::Chest => "chest",
            HitZone::Stomach => "stomach",
            HitZone::Arm => "arm",
            HitZone::Leg => "leg",
        }
    }

    pub fn from_name(name: &str) -> Option<HitZone> {
        HitZone::ALL.into_iter().find(|z| z.name() == name)
    }
}

/// A capsule: every point within `radius` of the segment from `a` to `b`. A
/// sphere when `a == b`.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Hitbox {
    pub zone: HitZone,
    pub a: Vec3,
    pub b: Vec3,
    pub radius: f32,
}

/// Everything the hitboxes depend on.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct HitboxPose {
    /// Feet position, world space.
    pub feet: Vec3,
    /// View yaw and pitch in radians, as in [`crate::player`] (pitch up is positive).
    pub yaw: f32,
    pub pitch: f32,
    pub stance: Stance,
    /// What the body is doing beyond its stance.
    pub activity: Activity,
}

/// The parts of a snapshot, beyond stance and view angles, that change how a
/// body is posed. All of them are in every snapshot (`PlayerView`).
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct Activity {
    pub sprinting: bool,
    /// Off the ground: jumping or falling.
    pub airborne: bool,
    /// Climbing over a ledge.
    pub mantling: bool,
    pub reloading: bool,
    /// Aim down sights, 0 at the hip to 1 aimed.
    pub ads: f32,
    /// World velocity (m/s): picks the walk, jog, or sprint and turns the
    /// legs toward a strafe. Snapshots carry none; it comes from the two
    /// snapshots a sample is blended between.
    pub velocity: Vec3,
    /// The weapon in hand, whose grips place the hands. `None` holds a rifle.
    pub weapon: Option<WeaponId>,
    /// How far along the stride, a reload, and a mantle the body is.
    pub progress: clock::Progress,
    /// How far down the body is between standing and crouched, 0 to 1
    /// (`MoveState::crouch`), while a stance change is under way. `None`
    /// takes it from the stance: fully in it.
    pub crouch: Option<f32>,
}

impl HitboxPose {
    /// A pose standing still with a rifle at the hip.
    pub fn new(feet: Vec3, yaw: f32, pitch: f32, stance: Stance) -> Self {
        Self {
            feet,
            yaw,
            pitch,
            stance,
            activity: Activity::default(),
        }
    }
}

