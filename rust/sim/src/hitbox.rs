//! Hit zones for one player: a head sphere and capsules for the neck, chest,
//! stomach, hips, arms, and legs, posed from what every machine knows about a
//! player: feet position, view angles, stance, and what they are doing
//! (sprinting, in the air, mantling, reloading, aiming, and which weapon).
//!
//! The shapes do not come from the animated skeleton. The dedicated server
//! never runs animation, and lag compensation (Phase 3) has to rebuild the
//! hitboxes a player had some ticks ago from a snapshot. A pure function of the
//! snapshot fields makes both cheap and the same on every machine.
//!
//! It still follows the animated body. Each state starts from a base pose
//! measured from the soldier's animation ([`poses`], generated by
//! `godot/tests/hitbox_fit_test.gd`), blended by speed as the character's
//! animation tree blends its loops ([`gait`]). Moving and climbing poses are
//! measured through the whole stride or climb and picked at the moment the
//! snapshot names ([`clock`]), so a running body's legs are where they are
//! drawn, not where they are on average. The hips turn toward a strafe
//! and the aim pitch bends the spine, neck, and head as the third-person
//! character's poser does, the weapon goes where the character holds it
//! ([`carry`], the same numbers the character uses), and two-bone IK puts the
//! arms on the weapon's grips. That Godot test poses a remote player through
//! every state and fails if a zone strays from the drawn body.
//!
//! Body space: +X is the character's right, +Y up, -Z forward, origin at the feet.

