/// One base pose: skeleton points with level aim, in body space.
#[derive(Clone, Copy)]
struct BasePose {
    hips: Vec3,
    /// Spine, chest, upper chest, neck, and head bone origins: the joints the
    /// aim pitch bends, in [`carry::PITCH_SHARES`] order.
    spine: [Vec3; 5],
    /// The head bone's basis.
    head: Mat3,
    /// Shoulder joints (upper arm origins), left then right.
    shoulders: [Vec3; 2],
    /// Hip, knee, and ankle, left leg then right leg.
    legs: [[Vec3; 3]; 2],
}

const fn v(x: f32, y: f32, z: f32) -> Vec3 {
    Vec3::new(x, y, z)
}

const fn m(x: Vec3, y: Vec3, z: Vec3) -> Mat3 {
    Mat3::from_cols(x, y, z)
}

/// Radii: head, neck, chest, stomach, upper arm, forearm, thigh, shin.
pub const HEAD_RADIUS: f32 = 0.135;
pub const NECK_RADIUS: f32 = 0.065;
pub const CHEST_RADIUS: f32 = 0.21;
pub const STOMACH_RADIUS: f32 = 0.17;
pub const UPPER_ARM_RADIUS: f32 = 0.065;
pub const FOREARM_RADIUS: f32 = 0.055;
pub const THIGH_RADIUS: f32 = 0.085;
pub const SHIN_RADIUS: f32 = 0.065;

impl BasePose {
    fn lerp(&self, to: &BasePose, t: f32) -> BasePose {
        let l = |a: Vec3, b: Vec3| a.lerp(b, t);
        let head = Mat3::from_cols(
            l(self.head.x_axis, to.head.x_axis),
            l(self.head.y_axis, to.head.y_axis),
            l(self.head.z_axis, to.head.z_axis),
        );
        BasePose {
            hips: l(self.hips, to.hips),
            spine: std::array::from_fn(|i| l(self.spine[i], to.spine[i])),
            head: orthonormal(head),
            shoulders: std::array::from_fn(|i| l(self.shoulders[i], to.shoulders[i])),
            legs: std::array::from_fn(|s| {
                std::array::from_fn(|j| l(self.legs[s][j], to.legs[s][j]))
            }),
        }
    }
}

/// The nearest rotation to a blended basis (Gram-Schmidt from +Y, then +Z).
fn orthonormal(m: Mat3) -> Mat3 {
    let y = m.y_axis.normalize();
    let z = (m.z_axis - y * m.z_axis.dot(y)).normalize();
    Mat3::from_cols(y.cross(z), y, z)
}

/// The base pose of a looping animation at `phase` (0..1, wrapping), blended
/// between the two measured samples around it.
fn cycle<const N: usize>(samples: &[BasePose; N], phase: f32) -> BasePose {
    let at = phase.rem_euclid(1.0) * N as f32;
    let i = (at.floor() as usize).min(N - 1);
    samples[i].lerp(&samples[(i + 1) % N], at - i as f32)
}

/// The base pose of a one-shot animation at `progress` (0..1), blended between
/// the two measured samples around it.
fn track<const N: usize>(samples: &[BasePose; N], progress: f32) -> BasePose {
    let at = progress.clamp(0.0, 1.0) * (N - 1) as f32;
    let i = (at.floor() as usize).min(N - 2);
    samples[i].lerp(&samples[i + 1], at - i as f32)
}

/// The animation the body is playing, as the character's animation tree picks
/// it: a mantle's climb or a vault over everything (blended in over the
/// start of the climb), then a vault's last pose while dropping off the far
/// side, then the jump in the air, then the stance.
fn base_pose(pose: &HitboxPose, speed: f32) -> BasePose {
    let activity = &pose.activity;
    if activity.mantling {
        let mantle = activity.progress.mantle;
        let climb = if activity.vaulting {
            track(&poses::VAULT, mantle)
        } else {
            track(&poses::CLIMB, mantle)
        };
        return ground_pose(pose, speed).lerp(&climb, gait::climb_share(mantle));
    }
    if activity.vaulting {
        return poses::VAULT[poses::CLIMB_SAMPLES - 1];
    }
    if activity.airborne {
        return poses::AIR;
    }
    ground_pose(pose, speed)
}

/// The pose on the ground: the idle blended into the loops by speed, each loop
/// at the snapshot's stride phase in the two measured directions around the
/// travel (`gait::POSE_DIRECTIONS`).
fn ground_pose(pose: &HitboxPose, speed: f32) -> BasePose {
    let activity = &pose.activity;
    let stride = activity.progress.stride;
    let moving = speed > gait::MOVING_SPEED;
    let (right, forward) = gait::local_velocity(activity.velocity, pose.yaw);
    let direction = gait::direction(right, forward, activity.sprinting);
    let (dir_a, dir_b, dir_t) = gait::pose_direction_samples(direction);
    let crouched = || {
        if moving {
            let walk = |d: usize| match d {
                0 => cycle(&poses::CROUCH_WALK, stride),
                d => cycle(&poses::DIRECTION_CROUCH_WALKS[d - 1], stride),
            };
            walk(dir_a).lerp(&walk(dir_b), dir_t)
        } else {
            poses::CROUCH
        }
    };
    // The standing loops in measured direction `d` at blend position `at`.
    let loops = |d: usize, at: f32| match d {
        0 => {
            let (a, b, t) = gait::stride_samples(at);
            cycle(&poses::STAND_STRIDES[a], stride)
                .lerp(&cycle(&poses::STAND_STRIDES[b], stride), t)
        }
        d => match gait::SPRINT_POSE_DIRECTIONS.iter().position(|s| *s == d) {
            // A forward diagonal runs on into its sprint, as forward does.
            Some(k) => {
                let sample = |i: usize| {
                    let table = match i.checked_sub(gait::DIRECTION_STRIDE_POSITIONS) {
                        None => &poses::DIRECTION_STRIDES[d - 1][i],
                        Some(i) => &poses::DIAGONAL_SPRINTS[k][i],
                    };
                    cycle(table, stride)
                };
                let (a, b, t) = gait::stride_samples(at);
                sample(a).lerp(&sample(b), t)
            }
            None => {
                let table = &poses::DIRECTION_STRIDES[d - 1];
                let (a, b, t) = gait::direction_stride_samples(at);
                cycle(&table[a], stride).lerp(&cycle(&table[b], stride), t)
            }
        },
    };
    let standing = || {
        if moving {
            let at = gait::stand_position(speed, activity.sprinting, direction);
            let blend = loops(dir_a, at).lerp(&loops(dir_b, at), dir_t);
            poses::STAND.lerp(&blend, gait::walk_share(at))
        } else if activity.progress.step > 0.0 {
            // Stepping round on the spot: the forward walk at the stride.
            poses::STAND.lerp(
                &loops(0, gait::WALK_SPEED),
                activity.progress.step * gait::TURN_STEP_WEIGHT,
            )
        } else {
            poses::STAND
        }
    };
    if pose.stance == Stance::Sliding {
        return poses::SLIDE;
    }
    // Partway through a stance change, the body is between the two, as the
    // drawn character blends them by the same eased amount.
    let full = match pose.stance {
        Stance::Crouching => 1.0,
        Stance::Prone => 2.0,
        _ => 0.0,
    };
    let blend = activity.crouch.unwrap_or(full);
    let down = crate::movement::crouch_ease(blend).max(activity.kneel.unwrap_or(0.0));
    let upright = if down <= 0.0 {
        standing()
    } else if down >= 1.0 {
        crouched()
    } else {
        standing().lerp(&crouched(), down)
    };
    // From a crouch on down to prone: lying still, or the low crawl at the
    // stride.
    let prone = crate::movement::prone_ease(blend);
    if prone <= 0.0 {
        return upright;
    }
    let lying = if moving {
        // The crawl in the two measured directions around the travel.
        let (a, b, t) = gait::prone_direction_samples(direction);
        cycle(&poses::PRONE_CRAWLS[a], stride).lerp(&cycle(&poses::PRONE_CRAWLS[b], stride), t)
    } else {
        poses::PRONE
    };
    if prone >= 1.0 {
        lying
    } else {
        upright.lerp(&lying, prone)
    }
}

/// The weapon carry a snapshot implies: fully in each state, as far into a
/// reload as the snapshot says.
fn carry_of(activity: &Activity) -> Carry {
    let on = |b: bool| if b { 1.0 } else { 0.0 };
    let def = activity.weapon.map(|w| w.def());
    Carry {
        ads: activity.ads,
        sprint: on(activity.sprinting),
        reload: on(activity.reloading),
        reload_progress: activity.progress.reload,
        class: def.map_or_else(Default::default, carry::CarryClass::of),
        timing: def.map_or_else(Default::default, carry::ReloadTiming::of),
        // A throw, or a vault's hand plant, drops the weapon out of the
        // support hand's way.
        // So does kneeling at the charge.
        swing: activity
            .throw
            .map_or(0.0, action::throw_weapon_drop)
            .max(vault_progress(activity).map_or(0.0, action::vault_weapon_drop))
            .max(if activity.kneel.is_some() { 1.0 } else { 0.0 }),
        ..Carry::default()
    }
}

/// How far through a vault the body is, if it is vaulting.
fn vault_progress(activity: &Activity) -> Option<f32> {
    (activity.mantling && activity.vaulting).then_some(activity.progress.mantle)
}

/// A planted hand's elbow bends out to the side and back (body space), and
/// the forearm reaches on from the wrist down onto the palm.
const VAULT_ELBOW: Vec3 = Vec3::new(-0.6, 1.1, 0.3);
const VAULT_PALM: Vec3 = Vec3::new(0.0, -0.04, -0.06);

/// Two-bone IK for an arm, as the character's poser solves it: the elbow and
/// the wrist for a shoulder at `root` reaching for `target`, bending toward
/// `pole`.
fn solve_arm(root: Vec3, target: Vec3, pole: Vec3) -> (Vec3, Vec3) {
    let (upper, lower) = (poses::UPPER_ARM, poses::FOREARM);
    let to_target = target - root;
    let reach_min = (upper - lower).abs() + 1e-4;
    let reach_max = upper + lower - 1e-4;
    let distance = to_target.length().clamp(reach_min, reach_max);
    let n = to_target.try_normalize().unwrap_or(Vec3::NEG_Y);
    let perpendicular = |p: Vec3| (p - n * p.dot(n)).try_normalize();
    let bend = perpendicular(pole - root)
        .or_else(|| perpendicular(Vec3::NEG_Y))
        .unwrap_or(Vec3::Z);
    let cos = ((upper * upper + distance * distance - lower * lower) / (2.0 * upper * distance))
        .clamp(-1.0, 1.0);
    let sin = (1.0 - cos * cos).max(0.0).sqrt();
    (root + (n * cos + bend * sin) * upper, root + n * distance)
}

/// The shapes for a pose, in world space.
pub fn hitboxes(pose: &HitboxPose) -> [Hitbox; COUNT] {
    let activity = &pose.activity;
    if activity.hound {
        return hound_hitboxes(pose.feet, pose.yaw);
    }
    let (right, forward) = gait::local_velocity(activity.velocity, pose.yaw);
    let speed = (right * right + forward * forward).sqrt();
    let base = base_pose(pose, speed);
    let slide = if pose.stance == Stance::Sliding {
        carry::SLIDE_PITCH_SCALE
    } else {
        1.0
    };
    // Lying along a slope, the body turns nose down by it about the eyes
    // (below), so the aim it holds is that much higher on the body.
    let tilt = lying_slope(pose);
    let pitch = (pose.pitch + tilt).clamp(-carry::MAX_PITCH, carry::MAX_PITCH) * slide;

    // The aim pitch bends each joint up the spine in turn; the shoulders ride
    // on the upper chest and the head turns with all of them.
    let mut hips = base.hips;
    let mut spine = base.spine;
    let mut shoulders = base.shoulders;
    let mut head = base.head;
    let mut legs = base.legs;

    // Every gait has a loop for its direction. Standing still, the hips stay
    // on the planted feet as the aim turns (`Progress::turn`), turning about
    // the feet, and the spine turns the rest.
    let moving = speed > gait::MOVING_SPEED && pose.stance != Stance::Sliding;
    // Lying down, the whole body turns with the aim about the eyes.
    let lying = pose.stance == Stance::Prone
        || activity
            .crouch
            .is_some_and(|c| crate::movement::prone_ease(c) > 0.0);
    let (lower_yaw, pivot) = if moving || lying {
        (0.0, hips)
    } else {
        (-activity.progress.turn, Vec3::ZERO)
    };
    if lower_yaw.abs() > 1e-4 {
        let turn = Mat3::from_axis_angle(Vec3::Y, lower_yaw);
        let about = |p: Vec3| pivot + turn * (p - pivot);
        spine = spine.map(about);
        shoulders = shoulders.map(about);
        legs = legs.map(|leg| leg.map(about));
        head = turn * head;
        hips = about(hips);
        for (i, share) in gait::TWIST_SHARES.into_iter().enumerate() {
            let back = Mat3::from_axis_angle(Vec3::Y, -lower_yaw * share);
            let pivot = spine[i];
            let about = |p: Vec3| pivot + back * (p - pivot);
            for joint in &mut spine[i + 1..] {
                *joint = about(*joint);
            }
            shoulders = shoulders.map(about);
            head = back * head;
        }
    }

    for (i, share) in carry::PITCH_SHARES.into_iter().enumerate() {
        let turn = Mat3::from_axis_angle(Vec3::X, pitch * share);
        let pivot = spine[i];
        let about = |p: Vec3| pivot + turn * (p - pivot);
        for joint in &mut spine[i + 1..] {
            *joint = about(*joint);
        }
        if i <= 2 {
            shoulders = shoulders.map(about);
        }
        head = turn * head;
    }
    // A zombie's hunch: the hips drop and go back, the spine bends forward
    // over them, and the head comes back up to look ahead.
    let hunch = activity.hunch.clamp(0.0, 1.0);
    if hunch > 0.0 {
        let shift = Vec3::new(0.0, -HUNCH_DROP, HUNCH_BACK) * hunch;
        hips += shift;
        spine = spine.map(|p| p + shift);
        shoulders = shoulders.map(|p| p + shift);
        for leg in &mut legs {
            leg[0] += shift;
        }
        let bend = Mat3::from_axis_angle(Vec3::X, -HUNCH_ANGLE * hunch);
        let about = |p: Vec3| hips + bend * (p - hips);
        spine = spine.map(about);
        shoulders = shoulders.map(about);
        // The upper back curves most: the neck reaches forward from the
        // upper chest.
        let curl = Mat3::from_axis_angle(Vec3::X, -HUNCH_NECK * hunch);
        let pivot = spine[2];
        for joint in &mut spine[3..] {
            *joint = pivot + curl * (*joint - pivot);
        }
        let tilt = HUNCH_ANGLE + HUNCH_NECK;
        head = Mat3::from_axis_angle(Vec3::X, tilt * HUNCH_HEAD_UP * hunch) * curl * bend * head;
    }
    // Holding a long gun, the upper chest blades (support shoulder forward)
    // and the neck turns back, so the head keeps facing the aim.
    let carry = carry_of(activity);
    // A throw, or a vault's hand plant, squares up while the support hand is
    // off the weapon.
    let blade = if activity.weapon.is_some() {
        let off = activity
            .throw
            .map_or(0.0, action::throw_hand_blend)
            .max(vault_progress(activity).map_or(0.0, action::vault_hand_blend));
        carry.blade() * (1.0 - off)
    } else {
        0.0
    };
    if blade > 0.0 {
        let axis = carry::blade_axis(pitch);
        let turn = Mat3::from_axis_angle(axis, -blade);
        let pivot = spine[2];
        let about = |p: Vec3| pivot + turn * (p - pivot);
        shoulders = shoulders.map(about);
        spine[3] = about(spine[3]);
        spine[4] = about(spine[4]);
        let back = Mat3::from_axis_angle(axis, blade);
        spine[4] = spine[3] + back * (spine[4] - spine[3]);
    }
    let [spine_joint, chest, upper_chest, neck, head_joint] = spine;
    let head_centre = head_joint + head * poses::HEAD_CENTRE;

    // The weapon at the eyes, the hands on its grips, the elbows from IK.
    let eyes = head_joint + head * carry::EYE_IN_HEAD;
    let weapon = carry::weapon_transform(eyes, pitch, &carry);
    let grips = activity
        .weapon
        .map_or_else(Grips::default, |w| Grips::held(w.def()));
    // Kneeling at the charge, the support hand is on the keypad.
    let support = match activity.kneel {
        Some(_) => (action::KNEEL_REACH, 1.0),
        None => carry.support_path(&grips),
    };
    let targets = carry::hand_targets(weapon, &grips, support);
    let pole = |p: Vec3| weapon.1 + weapon.0 * p;
    let arm = |(wrist_target, hand): (Vec3, Mat3), side: usize, hint: Vec3| {
        let (elbow, wrist) = solve_arm(shoulders[side], wrist_target, pole(hint));
        // The forearm reaches on past the wrist to the middle of the hand.
        (elbow, wrist + hand * poses::HAND_MIDDLE[side])
    };
    let [right_target, left_target] = targets;
    let (mut left_elbow, mut left_hand) = match activity.throw {
        // Throwing: the support hand carries the grenade, which is where
        // the forearm ends.
        Some(p) => {
            let blend = action::throw_hand_blend(p);
            let grenade = action::third_person_grenade(eyes, pitch, p);
            let (wrist_target, hand) = left_target;
            let (elbow, wrist) = solve_arm(
                shoulders[0],
                wrist_target.lerp(grenade, blend),
                pole(carry::LEFT_POLE),
            );
            (elbow, wrist + hand * poses::HAND_MIDDLE[0] * (1.0 - blend))
        }
        None => match vault_progress(activity) {
            // Vaulting: the support hand plants on the top.
            Some(p) => {
                let blend = action::vault_hand_blend(p);
                let (wrist_target, hand) = left_target;
                let plant = action::vault_plant(p);
                let pole = pole(carry::LEFT_POLE).lerp(VAULT_ELBOW, blend);
                let (elbow, wrist) = solve_arm(shoulders[0], wrist_target.lerp(plant, blend), pole);
                let middle = (hand * poses::HAND_MIDDLE[0]).lerp(VAULT_PALM, blend);
                (elbow, wrist + middle)
            }
            None => arm(left_target, 0, carry::LEFT_POLE),
        },
    };
    let (mut right_elbow, mut right_hand) = arm(right_target, 1, carry::RIGHT_POLE);
    if hunch > 0.0 {
        // A zombie's arms hang at its sides, bent at the elbow.
        let hang = |side: usize, sign: f32| {
            let target = Vec3::new(sign * HUNCH_HAND.x, HUNCH_HAND.y, HUNCH_HAND.z);
            let pole = shoulders[side] + Vec3::new(sign * 0.4, -0.2, 0.4);
            let (elbow, wrist) = solve_arm(shoulders[side], target, pole);
            (elbow, wrist + Vec3::new(0.0, -0.07, -0.02))
        };
        let (le, lh) = hang(0, -1.0);
        let (re, rh) = hang(1, 1.0);
        left_elbow = left_elbow.lerp(le, hunch);
        left_hand = left_hand.lerp(lh, hunch);
        right_elbow = right_elbow.lerp(re, hunch);
        right_hand = right_hand.lerp(rh, hunch);
    }

    let (s, c) = fmath::sin_cos(pose.yaw);
    let lie = Mat3::from_axis_angle(Vec3::X, -tilt);
    // Yaw turns -Z (forward) toward -X for positive yaw, as `movement::basis_from_yaw`.
    let world = |p: Vec3| {
        let p = PRONE_PIVOT + lie * (p - PRONE_PIVOT);
        pose.feet + Vec3::new(p.x * c + p.z * s, p.y, -p.x * s + p.z * c)
    };
    let shape = |zone, a: Vec3, b: Vec3, radius| Hitbox {
        zone,
        a: world(a),
        b: world(b),
        radius,
    };
    let [left_leg, right_leg] = legs;
    [
        shape(HitZone::Head, head_centre, head_centre, HEAD_RADIUS),
        shape(HitZone::Chest, neck, head_joint, NECK_RADIUS),
        shape(
            HitZone::Chest,
            chest.lerp(upper_chest, 0.3),
            upper_chest.lerp(neck, 0.5),
            CHEST_RADIUS,
        ),
        shape(
            HitZone::Stomach,
            hips.lerp(spine_joint, 0.3),
            spine_joint.lerp(chest, 0.6),
            STOMACH_RADIUS,
        ),
        shape(HitZone::Arm, shoulders[0], left_elbow, UPPER_ARM_RADIUS),
        shape(HitZone::Arm, left_elbow, left_hand, FOREARM_RADIUS),
        shape(HitZone::Arm, shoulders[1], right_elbow, UPPER_ARM_RADIUS),
        shape(HitZone::Arm, right_elbow, right_hand, FOREARM_RADIUS),
        shape(HitZone::Leg, left_leg[0], left_leg[1], THIGH_RADIUS),
        shape(HitZone::Leg, left_leg[1], left_leg[2], SHIN_RADIUS),
        shape(HitZone::Leg, right_leg[0], right_leg[1], THIGH_RADIUS),
        shape(HitZone::Leg, right_leg[1], right_leg[2], SHIN_RADIUS),
        // The hips, between the stomach and the legs.
        shape(
            HitZone::Stomach,
            left_leg[0].lerp(hips, 0.5),
            right_leg[0].lerp(hips, 0.5),
            STOMACH_RADIUS * 0.85,
        ),
    ]
}

/// A hound's hit zones (the model in `tools/build_hound.py`: 0.72 m at
/// the shoulder, 1.3 m nose to tail), in [`SHAPE_PARTS`]' order so hits
/// and reactions read alike: the head and muzzle, the chest, the belly,
/// the forelegs where a person's arms are, the hind legs where their legs
/// are, and the haunches as the hips.
pub fn hound_hitboxes(feet: Vec3, yaw: f32) -> [Hitbox; COUNT] {
    let (s, c) = fmath::sin_cos(yaw);
    // Body space: x right, y up, forward along -z.
    let world = |x: f32, y: f32, forward: f32| {
        let z = -forward;
        feet + Vec3::new(x * c + z * s, y, -x * s + z * c)
    };
    let shape = |zone, a: (f32, f32, f32), b: (f32, f32, f32), radius| Hitbox {
        zone,
        a: world(a.0, a.1, a.2),
        b: world(b.0, b.1, b.2),
        radius,
    };
    let leg = |x: f32, forward: f32, zone, upper: f32, lower: f32| {
        [
            shape(zone, (x, 0.52, forward), (x, 0.27, forward), upper),
            shape(zone, (x, 0.27, forward), (x, 0.04, forward), lower),
        ]
    };
    let [fl_upper, fl_lower] = leg(-0.11, 0.36, HitZone::Arm, 0.065, 0.045);
    let [fr_upper, fr_lower] = leg(0.11, 0.36, HitZone::Arm, 0.065, 0.045);
    let [hl_upper, hl_lower] = leg(-0.12, -0.36, HitZone::Leg, 0.08, 0.05);
    let [hr_upper, hr_lower] = leg(0.12, -0.36, HitZone::Leg, 0.08, 0.05);
    [
        shape(HitZone::Head, (0.0, 0.72, 0.6), (0.0, 0.72, 0.6), 0.13),
        shape(HitZone::Head, (0.0, 0.66, 0.68), (0.0, 0.64, 0.86), 0.07),
        shape(HitZone::Chest, (0.0, 0.56, 0.22), (0.0, 0.58, 0.46), 0.2),
        shape(HitZone::Stomach, (0.0, 0.55, -0.18), (0.0, 0.55, 0.2), 0.17),
        fl_upper,
        fl_lower,
        fr_upper,
        fr_lower,
        hl_upper,
        hl_lower,
        hr_upper,
        hr_lower,
        shape(
            HitZone::Stomach,
            (0.0, 0.56, -0.42),
            (0.0, 0.56, -0.2),
            0.17,
        ),
    ]
}

/// The nearest shape a ray hits.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct RayHit {
    pub zone: HitZone,
    /// Distance along the ray.
    pub distance: f32,
    /// Index into the hitbox array.
    pub index: usize,
}

/// Casts a ray from `origin` along `direction` (need not be normalised) up to
/// `max_distance` and returns the first shape it enters. A ray that starts inside
/// a shape hits it at distance 0.
pub fn raycast(
    boxes: &[Hitbox],
    origin: Vec3,
    direction: Vec3,
    max_distance: f32,
) -> Option<RayHit> {
    let length = direction.length();
    if length <= f32::EPSILON {
        return None;
    }
    let dir = direction / length;
    boxes
        .iter()
        .enumerate()
        .filter_map(|(index, b)| {
            ray_capsule(origin, dir, b.a, b.b, b.radius)
                .filter(|&t| t <= max_distance)
                .map(|distance| RayHit {
                    zone: b.zone,
                    distance,
                    index,
                })
        })
        .min_by(|x, y| x.distance.total_cmp(&y.distance))
}

/// Distance along a unit ray to the first point inside a capsule, if any.
fn ray_capsule(origin: Vec3, dir: Vec3, a: Vec3, b: Vec3, radius: f32) -> Option<f32> {
    let axis = b - a;
    let axis_len_sq = axis.length_squared();
    if axis_len_sq <= f32::EPSILON {
        return ray_sphere(origin, dir, a, radius);
    }
    // Inside already?
    if distance_sq_to_segment(origin, a, b) <= radius * radius {
        return Some(0.0);
    }
    // Infinite cylinder around the axis, then clip to the segment; the caps are spheres.
    let ao = origin - a;
    let d_axis = dir.dot(axis) / axis_len_sq;
    let o_axis = ao.dot(axis) / axis_len_sq;
    let d_perp = dir - axis * d_axis;
    let o_perp = ao - axis * o_axis;
    let qa = d_perp.length_squared();
    let qb = 2.0 * d_perp.dot(o_perp);
    let qc = o_perp.length_squared() - radius * radius;
    let mut best: Option<f32> = None;
    if qa > f32::EPSILON {
        let disc = qb * qb - 4.0 * qa * qc;
        if disc >= 0.0 {
            let t = (-qb - disc.sqrt()) / (2.0 * qa);
            let along = o_axis + t * d_axis;
            if t >= 0.0 && (0.0..=1.0).contains(&along) {
                best = Some(t);
            }
        }
    }
    for cap in [a, b] {
        if let Some(t) = ray_sphere(origin, dir, cap, radius) {
            best = Some(best.map_or(t, |x| x.min(t)));
        }
    }
    best
}

fn ray_sphere(origin: Vec3, dir: Vec3, centre: Vec3, radius: f32) -> Option<f32> {
    let oc = origin - centre;
    let c = oc.length_squared() - radius * radius;
    if c <= 0.0 {
        return Some(0.0);
    }
    let b = oc.dot(dir);
    if b > 0.0 {
        return None;
    }
    let disc = b * b - c;
    if disc < 0.0 {
        return None;
    }
    Some(-b - disc.sqrt())
}

fn distance_sq_to_segment(p: Vec3, a: Vec3, b: Vec3) -> f32 {
    let ab = b - a;
    let t = ((p - a).dot(ab) / ab.length_squared()).clamp(0.0, 1.0);
    (a + ab * t - p).length_squared()
}

