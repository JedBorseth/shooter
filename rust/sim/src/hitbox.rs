/// Where a shot landed on a body.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum HitZone {
    Head,
    /// Neck, chest, and shoulders.
    Chest,
    Stomach,
    Arm,
    Leg,
}

impl HitZone {
    pub const ALL: [HitZone; 5] = [
        HitZone::Head,
        HitZone::Chest,
        HitZone::Stomach,
        HitZone::Arm,
        HitZone::Leg,
    ];

    /// Name used in collider metadata (`hit_zone`) and debug output.
    pub fn name(self) -> &'static str {
        match self {
            HitZone::Head => "head",
            HitZone::Chest => "chest",
            HitZone::Stomach => "stomach",
            HitZone::Arm => "arm",
            HitZone::Leg => "leg",
        }
    }

    pub fn from_name(name: &str) -> Option<HitZone> {
        HitZone::ALL.into_iter().find(|z| z.name() == name)
    }
}

/// A capsule: every point within `radius` of the segment from `a` to `b`. A
/// sphere when `a == b`.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Hitbox {
    pub zone: HitZone,
    pub a: Vec3,
    pub b: Vec3,
    pub radius: f32,
}

/// Everything the hitboxes depend on.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct HitboxPose {
    /// Feet position, world space.
    pub feet: Vec3,
    /// View yaw and pitch in radians, as in [`crate::player`] (pitch up is positive).
    pub yaw: f32,
    pub pitch: f32,
    pub stance: Stance,
    /// What the body is doing beyond its stance.
    pub activity: Activity,
}

/// The parts of a snapshot, beyond stance and view angles, that change how a
/// body is posed. All of them are in every snapshot (`PlayerView`).
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct Activity {
    pub sprinting: bool,
    /// Off the ground: jumping or falling.
    pub airborne: bool,
    /// Climbing over a ledge.
    pub mantling: bool,
    /// Vaulting over thin cover: while mantling, the vault's own poses and
    /// the support hand planted on the top ([`action::vault_plant`]); in the
    /// air after it, the vault's last pose, reaching for the ground.
    pub vaulting: bool,
    pub reloading: bool,
    /// Aim down sights, 0 at the hip to 1 aimed.
    pub ads: f32,
    /// World velocity (m/s): picks the walk, jog, or sprint and turns the
    /// legs toward a strafe. Snapshots carry none; it comes from the two
    /// snapshots a sample is blended between.
    pub velocity: Vec3,
    /// The weapon in hand, whose grips place the hands. `None` holds a rifle.
    pub weapon: Option<WeaponId>,
    /// How far along the stride, a reload, and a mantle the body is.
    pub progress: clock::Progress,
    /// How far down the body is, 0 standing to 1 crouched to 2 prone
    /// (`MoveState::crouch`), while a stance change is under way. `None`
    /// takes it from the stance: fully in it.
    pub crouch: Option<f32>,
    /// A zombie's hunch, 0 (a soldier) to 1: the hips low and back, the
    /// spine bent forward, the head pushed out, and the arms hanging at the
    /// sides instead of holding a weapon, as the shamble is drawn. Zombies
    /// are not networked; snapshots never carry it.
    pub hunch: f32,
    /// A Zombies hound ([`crate::zombies::hounds`]): four-legged hit zones
    /// ([`hound_hitboxes`]) instead of a person's. Snapshots never carry it.
    pub hound: bool,
    /// How far along a grenade throw the body is (`PlayerView::throw`), if
    /// throwing: the support arm follows the grenade ([`action`]).
    pub throw: Option<f32>,
    /// Kneeling at Search and Destroy's charge to plant or defuse it, and
    /// how far down (0..1, [`action::kneel`]): the body goes as low as a
    /// crouch, the weapon drops, and the support hand reaches for the
    /// keypad ([`action::KNEEL_REACH`]), as the character draws it.
    pub kneel: Option<f32>,
    /// Lying prone, how far along the ground the body lies (radians,
    /// positive with the legs higher than the chest; `PlayerView::
    /// prone_slope`): the lying body turns about the eyes
    /// ([`PRONE_PIVOT`]) to lie along it, the aim staying where it was.
    pub slope: f32,
}

/// What a prone body lying along a slope turns about: the eyes, which sit
/// over the player's origin prone (body space; the prone eye height).
pub const PRONE_PIVOT: Vec3 = Vec3::new(0.0, 0.39, 0.0);
/// How far behind the eyes the ground under a prone body's knees is
/// measured (m), and the steepest slope it lies along (radians).
pub const PRONE_SLOPE_SPAN: f32 = 1.1;
pub const MAX_PRONE_SLOPE: f32 = 30.0 * std::f32::consts::PI / 180.0;

/// How far a body lies along its slope (radians): the slope, as far as the
/// body is down from a crouch to prone.
pub fn lying_slope(pose: &HitboxPose) -> f32 {
    let activity = &pose.activity;
    let full = if pose.stance == Stance::Prone {
        2.0
    } else {
        0.0
    };
    let blend = activity.crouch.unwrap_or(full);
    activity.slope.clamp(-MAX_PRONE_SLOPE, MAX_PRONE_SLOPE) * crate::movement::prone_ease(blend)
}

impl HitboxPose {
    /// A pose standing still with a rifle at the hip.
    pub fn new(feet: Vec3, yaw: f32, pitch: f32, stance: Stance) -> Self {
        Self {
            feet,
            yaw,
            pitch,
            stance,
            activity: Activity::default(),
        }
    }
}

/// A zombie's hunch (`Activity::hunch`), fitted to the drawn shamble's neck
/// and head joints: the hips this much lower (negative: higher) and further
/// back (m), the spine bent forward over the hips this far and the neck
/// this much more from the upper chest (radians), the head turned back up by
/// this share of the bend, and the wrists hanging here (body space, the right
/// hand's; the left mirrors it).
const HUNCH_DROP: f32 = -0.04;
const HUNCH_BACK: f32 = 0.1;
const HUNCH_ANGLE: f32 = 0.7;
const HUNCH_NECK: f32 = 0.1;
const HUNCH_HEAD_UP: f32 = 0.6;
const HUNCH_HAND: Vec3 = Vec3::new(0.36, 0.95, -0.02);

