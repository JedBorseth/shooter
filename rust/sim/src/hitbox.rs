    #[test]
    fn reloading_takes_the_support_hand_to_the_vest() {
        let held = with(Activity {
            weapon: m4(),
            ..Activity::default()
        });
        // Mid-reload, the support hand at the pouch.
        let reloading = with(Activity {
            reloading: true,
            weapon: m4(),
            progress: clock::Progress {
                reload: carry::MID_RELOAD,
                ..clock::Progress::default()
            },
            ..Activity::default()
        });
        // Just started: still on the weapon.
        let starting = with(Activity {
            reloading: true,
            weapon: m4(),
            ..Activity::default()
        });
        let feet = pose(Stance::Standing).feet;
        let reach = |b: &[Hitbox; COUNT]| -(b[LEFT_HAND].b.z - feet.z);
        assert!((reach(&starting) - reach(&held)).abs() < 0.05);
        assert!(
            reach(&reloading) < reach(&held) - 0.1,
            "the hand comes back"
        );
        assert!(reloading[LEFT_HAND].b.y < held[LEFT_HAND].b.y);
    }

